-- สัดส่วนน้ำคั้นแท้ต่อปริมาณน้ำสุดท้าย — แกะจากเว็บเก่า cal.joolzjuice.com
--
-- สูตรน้ำส้ม Joolz (เจ้าของยืนยัน 14 ส.ค. 69, ซอร์ส PHP อยู่ในโฟลเดอร์
-- cal.joolzjuice.com ใน repo): น้ำส้มคั้นแท้ 70% ของปริมาณรวม · น้ำตาล =
-- (Brix เป้า × ปริมาณรวม − Brix วัดได้ × น้ำคั้น) / 100 · น้ำ = ที่เหลือ
-- น้ำเชื่อม = น้ำตาล × 2 (เข้มข้นครึ่งต่อครึ่ง) หักน้ำออกเท่าน้ำตาล
-- เกลือ 0.05% + แซคส้ม 1% เก็บเป็น "ของเติมต่อลิตร" ใน production_recipe_items
--
-- ทิศทางกลับด้านจากที่ทำรอบแรก: กรอก "จะทำกี่ลิตร" → ระบบบอกต้องใช้น้ำคั้น
-- เท่าไหร่ (ไม่ใช่กรอกน้ำคั้นที่มี) — ตรง workflow จริงของโรงงาน

alter table public.production_recipes
  add column juice_ratio numeric not null default 70;

