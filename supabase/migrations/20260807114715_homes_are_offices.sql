-- บ้านปู / บ้านขวัญ = office ไม่ใช่ home (ตัดสินใจ 2026-08-07)
--
-- ข้อมูลจริงพิสูจน์ว่าไม่ใช่บ้านส่วนตัว แต่เป็นจุดทำงานร่วม:
--   บ้านปู ADF  — 8 คนเช็คอินประจำ (ปู 215 · เนม 38 · แพท 20 · Phai 14 · ไกด์ 9 ...)
--   บ้านขวัญ    — 7 คน และคนที่ใช้มากสุดคือพีช 70 ครั้ง ส่วนขวัญเจ้าของบ้านแค่ 6 ครั้ง
--
-- ถ้าตั้งเป็น home + ผูกเจ้าของ อีก 6-7 คนจะเช็คอินไม่ได้
-- ═══════════════════════════════════════════════════════════════════

update location_corrections
set new_location_type = 'office',
    evidence = evidence || ' · แก้: ข้อมูลจริงมีคนเช็คอินประจำ 7-8 คน ไม่ใช่บ้านส่วนตัว → office'
where firestore_name in ('บ้านปู ADF', 'บ้านขวัญ');

update locations set location_type = 'office'
where name in ('บ้านปู ADF', 'บ้านขวัญ');

comment on column locations.location_type is
  'office=สำนักงาน/คลัง/จุดทำงาน · mall=เคาน์เตอร์ห้าง(PC) · event=ออกบูธ · home=บ้านพนักงาน(ยังไม่ได้ใช้)';

-- users.home_lat/lng ยังเก็บไว้ — ใช้กับ WFH จริง ๆ (โฟน/มิว/มาร์ค) ไม่ใช่ 2 ที่นี้
comment on column users.home_lat is
  'พิกัดบ้านสำหรับคนที่ WFH จริง — ไม่เกี่ยวกับ "บ้านปู"/"บ้านขวัญ" ซึ่งเป็นจุดทำงานร่วม (office)';
