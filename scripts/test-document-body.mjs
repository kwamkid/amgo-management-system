// ตัวแปลเนื้อหาเอกสาร: ข้อความที่พิมพ์ → บล็อก
//
// ── ทำไมต้องมีเทสต์ ─────────────────────────────────────────────────
// ตัวแปลตัวนี้เป็น "ต้นทางเดียว" ของทั้งแผ่น A4 (PDF) และไฟล์ Word
// แปลผิด = เอกสารบริษัทที่ส่งออกไปแล้วผิดทั้งสองไฟล์พร้อมกัน
// และผิดแบบเงียบ ๆ ด้วย — ไม่มี error ให้เห็น มีแต่หัวข้อที่กลายเป็นย่อหน้า
//
// รัน: node scripts/test-document-body.mjs   (ไม่ต้องต่อฐานข้อมูล)

import { parseBody, blocksToText } from '../lib/documents/types.ts'

let pass = 0
let fail = 0

const check = (ok, name, detail = '') => {
  if (ok) {
    pass++
    console.log(`  ✅ ${name}`)
  } else {
    fail++
    console.log(`  ❌ ${name}${detail ? ` — ${detail}` : ''}`)
  }
}

const eq = (got, want, name) =>
  check(
    JSON.stringify(got) === JSON.stringify(want),
    name,
    `ได้ ${JSON.stringify(got)}`
  )

console.log('\nตัวแปลเนื้อหาเอกสาร\n')

// ── พื้นฐาน ────────────────────────────────────────────────────────
eq(parseBody(''), [], 'ข้อความว่าง = ไม่มีบล็อก')
eq(parseBody('   \n\n  \n'), [], 'มีแต่บรรทัดว่าง = ไม่มีบล็อก')

eq(
  parseBody('สวัสดีครับ'),
  [{ kind: 'paragraph', text: 'สวัสดีครับ' }],
  'บรรทัดธรรมดา = ย่อหน้า'
)

eq(
  parseBody('บรรทัดหนึ่ง\nบรรทัดสอง'),
  [
    { kind: 'paragraph', text: 'บรรทัดหนึ่ง' },
    { kind: 'paragraph', text: 'บรรทัดสอง' },
  ],
  'กด Enter หนึ่งครั้ง = ย่อหน้าใหม่ (ไม่ต้องเว้นบรรทัด)'
)

// ── หัวข้อ ─────────────────────────────────────────────────────────
eq(
  parseBody('# สินค้าที่ร่วมแคมเปญ'),
  [{ kind: 'heading', text: 'สินค้าที่ร่วมแคมเปญ' }],
  '# นำหน้า = หัวข้อ และตัด # กับช่องว่างออก'
)
eq(
  parseBody('###   ซ้อนกันหลายตัว'),
  [{ kind: 'heading', text: 'ซ้อนกันหลายตัว' }],
  '# หลายตัวก็ยังเป็นหัวข้อเดียว'
)
eq(parseBody('#'), [], '# เปล่า ๆ ไม่มีข้อความ = ไม่เกิดบล็อก')

// ── รายการ ─────────────────────────────────────────────────────────
eq(
  parseBody('- ข้อหนึ่ง\n- ข้อสอง'),
  [{ kind: 'bullet', items: ['ข้อหนึ่ง', 'ข้อสอง'] }],
  'บรรทัด - ที่ติดกัน รวมเป็นรายการเดียว'
)
eq(
  parseBody('* ดาว\n• จุด\n- ขีด'),
  [{ kind: 'bullet', items: ['ดาว', 'จุด', 'ขีด'] }],
  'รับทั้ง - * • ปนกันได้'
)
eq(
  parseBody('-ไม่เว้นวรรค'),
  [{ kind: 'bullet', items: ['ไม่เว้นวรรค'] }],
  'ไม่เว้นวรรคหลังขีดก็ยังเป็นรายการ'
)

// รายการที่ถูกคั่น ต้องแยกเป็นคนละก้อน ไม่ใช่รวมข้ามหัวข้อ
eq(
  parseBody('- ก\n# หัวข้อ\n- ข'),
  [
    { kind: 'bullet', items: ['ก'] },
    { kind: 'heading', text: 'หัวข้อ' },
    { kind: 'bullet', items: ['ข'] },
  ],
  'หัวข้อคั่นกลาง = รายการแยกกัน 2 ก้อน'
)

// ⚠️ ข้อนี้สำคัญ: บรรทัดว่างไม่ใช่ตัวคั่นรายการ ถ้าเผลอทำให้เป็นตัวคั่น
//    คนที่เว้นบรรทัดให้อ่านง่ายจะได้รายการที่ระยะห่างถ่างผิดโดยไม่รู้ตัว
eq(
  parseBody('- ก\n\n- ข'),
  [{ kind: 'bullet', items: ['ก', 'ข'] }],
  'บรรทัดว่างระหว่างรายการ ไม่ทำให้รายการขาดจากกัน'
)

// ── ของจริง: จดหมายตัวอย่างที่เจ้าของส่งมา ──────────────────────────
const LETTER = `เพื่อสร้างแรงผลักดันและเพิ่มโอกาสปิดการขาย บริษัทขอประกาศ ดังนี้
# สินค้าที่ร่วมแคมเปญ
- รถเข็น Swan Pro ชิ้นละ 200 บาท
- STOKKE : Sleepi ชิ้นละ 500 บาท
# เงื่อนไขรับรางวัลพิเศษ
- นับยอดขายตั้งแต่ 1 ก.ย. – 31 ต.ค. 2569
ขอให้ทุกท่านใช้โอกาสนี้สร้างผลงาน`

const blocks = parseBody(LETTER)
check(blocks.length === 6, 'จดหมายตัวอย่างได้ 6 บล็อก', `ได้ ${blocks.length}`)
check(
  blocks.filter((b) => b.kind === 'heading').length === 2,
  'จดหมายตัวอย่างมีหัวข้อ 2 อัน'
)
check(
  blocks.filter((b) => b.kind === 'bullet').length === 2,
  'จดหมายตัวอย่างมีรายการ 2 ก้อน'
)

// ── แปลไปแล้วแปลกลับ ต้องได้เท่าเดิม ───────────────────────────────
// ใช้ตอนกู้คืนรุ่นเก่าที่เก็บเป็นบล็อกไว้ ถ้าไม่ตรงกัน เอกสารจะเพี้ยน
// ทุกครั้งที่กดกู้คืน โดยไม่มีอะไรฟ้อง
eq(
  parseBody(blocksToText(blocks)),
  blocks,
  'บล็อก → ข้อความ → บล็อก ได้ผลเท่าเดิม'
)

console.log(`\nผ่าน ${pass} · ไม่ผ่าน ${fail}\n`)
process.exit(fail ? 1 : 0)
