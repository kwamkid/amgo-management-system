/**
 * สุ่มคำอวยพร — ให้ผลเหมือนเดิมสำหรับ (คน, วัน) เดียวกัน
 *
 * ตั้งใจไม่ใช้ Math.random() เพราะถ้า cron ยิงซ้ำวันเดียวกัน
 * (เน็ตหลุดแล้ว retry) จะได้ข้อความคนละอัน ดูเหมือนอวยพรสองรอบ
 */
export function pickBirthdayMessage(userId: string, dateKey: string): string {
  let hash = 0
  const seed = `${userId}|${dateKey}`
  for (let i = 0; i < seed.length; i++) {
    hash = (hash * 31 + seed.charCodeAt(i)) | 0
  }
  return BIRTHDAY_MESSAGES[Math.abs(hash) % BIRTHDAY_MESSAGES.length]
}
