-- 0008 — โควตาลาตามขั้นต่ำกฎหมายแรงงานไทย
--
-- พ.ร.บ. คุ้มครองแรงงาน พ.ศ. 2541 (+ ฉบับที่ 7 พ.ศ. 2562)
--   ลาป่วย    ม.32 + ม.57    ลาได้เท่าที่ป่วยจริง แต่จ่ายค่าจ้างไม่เกิน 30 วันทำงาน/ปี
--   ลากิจ     ม.34 + ม.57/1  ไม่น้อยกว่า 3 วันทำงาน/ปี โดยได้รับค่าจ้าง
--   ลาพักร้อน ม.30           ไม่น้อยกว่า 6 วันทำงาน/ปี (ต้องทำงานครบ 1 ปีก่อน)
--
-- หมายเหตุ: 30 ของลาป่วยเป็น "เพดานที่ได้ค่าจ้าง" (ป่วยเกินได้แต่ไม่ได้เงิน)
--          ส่วน 3 กับ 6 เป็น "ขั้นต่ำ" ที่บริษัทให้มากกว่าได้
-- ═══════════════════════════════════════════════════════════════════════

update leave_types set default_days = 30, requires_attachment = true  where code = 'sick';
update leave_types set default_days = 3,  requires_attachment = false where code = 'personal';
update leave_types set default_days = 6,  requires_attachment = false where code = 'vacation';

comment on column leave_types.default_days is
  'ขั้นต่ำตามกฎหมายแรงงานไทย — sick 30 คือเพดานที่ได้ค่าจ้าง ส่วน personal 3 / vacation 6 คือขั้นต่ำที่ให้มากกว่าได้';
comment on column leave_types.requires_attachment is
  'ลาป่วยตั้งแต่ 3 วันทำงานขึ้นไป นายจ้างขอใบรับรองแพทย์ได้ (ม.32)';
